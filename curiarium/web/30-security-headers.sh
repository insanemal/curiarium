#!/bin/sh
set -eu

# Regenerates /etc/nginx/security-headers.conf from SECURITY_HEADERS_* env vars.
# Runs from /docker-entrypoint.d as UID 101 before nginx starts.

# The entrypoint never sets SECURITY_HEADERS_CONF_PATH; only the host-side CSP
# test does, so it can generate a policy into a temporary file.
conf_path=${SECURITY_HEADERS_CONF_PATH:-/etc/nginx/security-headers.conf}
tmp_path="${conf_path}.tmp.$$"

default_content_type_options='nosniff'
default_referrer_policy='strict-origin-when-cross-origin'
default_frame_options='DENY'
default_permissions_policy='camera=(), microphone=(), geolocation=()'
default_hsts='max-age=31536000'

# Header values are interpolated verbatim into nginx configuration, so quotes,
# `$` (nginx variable interpolation) and control characters must never reach
# the emitted file. The trailing sentinel keeps `$( )` from swallowing a
# trailing newline before the comparison.
is_safe_value() {
  value=$1
  case "$value" in
    *'"'*) return 1 ;;
    *'$'*) return 1 ;;
    *'\'*) return 1 ;;
  esac
  stripped=$(printf '%sX' "$value" | LC_ALL=C tr -d '\000-\037\177')
  [ "$stripped" = "${value}X" ]
}

# The browser talks to the same origin by default. When an absolute API URL is
# configured (split-host deployment) that origin must be allowed by connect-src
# (fetch/XHR) and img-src (thumbnails and project covers served by the API),
# otherwise API calls and every image are blocked by the CSP. The derived origin
# is also interpolated into nginx config, so validate it before use.
api_url="${VITE_API_URL:-}"
if [ -z "$api_url" ] && [ -n "${PUBLIC_URL:-}" ]; then
  api_url="${PUBLIC_URL%/}/api"
fi
api_origin=""
case "$api_url" in
  http://* | https://*) api_origin=$(printf '%s' "$api_url" | sed 's#^\(https\?://[^/?]*\).*#\1#') ;;
esac
if [ -n "$api_origin" ] && ! is_safe_value "$api_origin"; then
  printf '[security-headers] WARNING: ignoring unsafe derived API origin for connect-src and img-src; using self only\n' >&2
  api_origin=""
fi

# The API origin is vetted once above and consumed by both directives, so
# connect-src and img-src cannot drift apart.
api_sources="'self'"
if [ -n "$api_origin" ] && [ "$api_origin" != "'self'" ]; then
  api_sources="$api_sources $api_origin"
fi

# No media-src: nothing in curiarium/web/src renders <audio> or <video>. Adding
# it would force a matching edit to the serialised baked security-headers.conf.
default_csp="default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; style-src 'self' 'unsafe-inline'; img-src $api_sources data: blob:; font-src 'self' data:; connect-src $api_sources; worker-src 'self' blob:; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'"

lowercase() {
  printf '%s' "$1" | tr '[:upper:]' '[:lower:]'
}

is_enabled() {
  case "$(lowercase "${1:-}")" in
    1 | true | yes | y | on) return 0 ;;
    *) return 1 ;;
  esac
}

is_off() {
  case "$(lowercase "${1:-}")" in
    off) return 0 ;;
    *) return 1 ;;
  esac
}

# emit_header <name> <configured value> <default value>
emit_header() {
  name=$1
  value=$2
  fallback=$3

  if [ -z "$value" ]; then
    value=$fallback
  fi

  if is_off "$value"; then
    return 0
  fi

  if ! is_safe_value "$value"; then
    printf '[security-headers] WARNING: ignoring unsafe %s value (quotes, $, backslash, or control characters); using default\n' "$name" >&2
    value=$fallback
  fi

  if [ -z "$value" ]; then
    return 0
  fi

  printf 'add_header %s "%s" always;\n' "$name" "$value"
}

trap 'rm -f "$tmp_path"' EXIT HUP INT TERM

if is_enabled "${SECURITY_HEADERS_ENABLED:-true}"; then
  {
    printf '# Generated by 30-security-headers.sh; edits are overwritten on restart.\n'
    emit_header X-Content-Type-Options "${SECURITY_HEADERS_CONTENT_TYPE_OPTIONS:-}" "$default_content_type_options"
    emit_header Referrer-Policy "${SECURITY_HEADERS_REFERRER_POLICY:-}" "$default_referrer_policy"
    emit_header X-Frame-Options "${SECURITY_HEADERS_FRAME_OPTIONS:-}" "$default_frame_options"
    emit_header Permissions-Policy "${SECURITY_HEADERS_PERMISSIONS_POLICY:-}" "$default_permissions_policy"
    emit_header Strict-Transport-Security "${SECURITY_HEADERS_HSTS:-}" "$default_hsts"
    emit_header Content-Security-Policy "${SECURITY_HEADERS_CSP:-}" "$default_csp"
  } >"$tmp_path"
else
  printf '# Generated by 30-security-headers.sh; all security headers disabled by SECURITY_HEADERS_ENABLED.\n' >"$tmp_path"
fi

chmod 644 "$tmp_path"
mv "$tmp_path" "$conf_path"
